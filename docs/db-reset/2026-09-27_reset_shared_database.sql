-- ===== B. 019_shifts.sql ==============================================
-- 019_shifts.sql
-- Shift handover (guide 7.3). One row per shift a carer starts; ended_at is
-- set when the shift is closed. The handover collects notes by carer_id and
-- created_at within the shift, so visit_notes needs no new column.
-- Additive only. Do not edit this file after it has been run anywhere —
-- later changes go in a new numbered file.

create table if not exists public.shifts (
  id uuid primary key default gen_random_uuid(),
  carer_id uuid references auth.users (id),
  carer_name text,
  started_at timestamptz not null default now(),
  ended_at timestamptz
);

alter table public.shifts enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'shifts'
      and policyname = 'shifts_authenticated_all'
  ) then
    -- Dev policy: any signed-in user can read/write; anon gets nothing.
    create policy "shifts_authenticated_all"
      on public.shifts
      for all
      to authenticated
      using (true)
      with check (true);
  end if;
end $$;

-- ===== B. 020_resident_role.sql =======================================
-- 020_resident_role.sql
-- Resident app (guide chapter 10). Adds 'resident' as a valid user role and
-- links a resident's login to their residents row.
--
-- NOTE: this file is a deliberate one-off exception to "additive only".
-- user_profiles.role has a CHECK constraint limiting it to the old role
-- list; a check constraint cannot be widened in place, so it is dropped and
-- re-added with 'resident' included. No rows are changed or removed.
-- The constraint is found by its definition rather than by name, because
-- the name was auto-generated.
-- Do not edit this file after it has been run anywhere — later changes go
-- in a new numbered file.

do $$
declare
  c record;
begin
  for c in
    select conname
    from pg_constraint
    where conrelid = 'public.user_profiles'::regclass
      and contype = 'c'
      and pg_get_constraintdef(oid) ilike '%role%'
  loop
    execute format('alter table public.user_profiles drop constraint %I', c.conname);
  end loop;
end $$;

alter table public.user_profiles
  add constraint user_profiles_role_check
  check (role in ('superadmin', 'admin', 'staff', 'caregiver', 'family', 'resident'));

alter table public.user_profiles
  add column if not exists resident_id uuid references public.residents (id);

-- ===== B. 021_seed_resident_auth_profile.sql ==========================
-- 021_seed_resident_auth_profile.sql
-- Links a demo resident login to a profile row with role 'resident' and to
-- the first resident in the residents table.
-- Prerequisite (manual, not SQL): create the matching Supabase Auth user
-- first, in Dashboard > Authentication > Users > Add user:
--   email    resident_123@aethon.local
--   password (whatever you'll sign in with on the email/password form)
--   check "Auto Confirm User"
-- Run 020 first. Additive only. Do not edit this file after it has been run
-- anywhere — later changes go in a new numbered file.

insert into public.user_profiles (id, role, full_name, resident_id)
select
  u.id,
  'resident',
  (select first_name from public.residents order by created_at limit 1),
  (select id from public.residents order by created_at limit 1)
from auth.users u
where u.email = 'resident_123@aethon.local'
on conflict (id) do update set
  role = excluded.role,
  full_name = excluded.full_name,
  resident_id = excluded.resident_id;

