-- One-off reset of the shared Supabase project 'aethon' (Zurich), 27 Sep 2026.
-- NOT a migration: do not run on any other database.
--
-- Why: the database held two designs at once (the build guide's clients /
-- client_id tables and this app's residents / resident_id tables). This app is
-- now the single codebase for iOS and Android, so its schema becomes the only
-- one.
--
-- What it does, in one transaction (any error rolls back everything):
--   A. Moves every table currently in public into schema archive_2026_09_27.
--      Nothing is deleted; undo with: alter table archive_2026_09_27.<name> set schema public;
--   B. Runs docs/sql/001 to 026 unchanged and in order, except 011: its
--      "add table if not exists" is not valid Postgres, so an equivalent
--      guarded block is used instead.
--   C. Lists the resulting tables with row counts.
-- Not touched: auth users and settings, storage (media bucket), the earlier
-- archive schema legacy_colleague.

begin;

-- ===== A. Archive the current public tables =================================
create schema if not exists archive_2026_09_27;
revoke all on schema archive_2026_09_27 from anon, authenticated;

do $$
declare t text;
begin
  -- Take archived tables out of realtime so they no longer broadcast changes.
  for t in select tablename from pg_publication_tables
           where pubname = 'supabase_realtime' and schemaname = 'public'
  loop
    execute format('alter publication supabase_realtime drop table public.%I', t);
  end loop;
  for t in select table_name from information_schema.tables
           where table_schema = 'public' and table_type = 'BASE TABLE'
  loop
    execute format('alter table public.%I set schema archive_2026_09_27', t);
  end loop;
end $$;

-- ===== B. 001_base_schema.sql =========================================
-- 001_base_schema.sql
-- Base schema for an empty Supabase project. Additive only: safe to run
-- once against a fresh project. Do not edit this file after it has been
-- run anywhere — later changes go in a new numbered file.
--
-- Tables:
--   facilities    A care facility (nursing home / community). The top of
--                 the tenancy tree: every profile and resident belongs to
--                 exactly one facility.
--   user_profiles One row per auth.users row, holding the app-specific
--                 fields (role, display name, which facility/nurse ID
--                 they belong to) that Supabase Auth doesn't store.
--   residents     A resident of a facility, as shown on caregiver and
--                 family screens (roster, home dashboard, etc).
--   visit_notes   A caregiver's log entry for a visit/check-in with a
--                 resident (mood, tasks completed, free-text notes).
--   escalations   A concern a caregiver raises about a resident that
--                 needs follow-up; tracked open/resolved.
--   wellbeing_logs Point-in-time wellbeing readings for a resident
--                 (mood/sleep/pain/weight) shown on trend screens.
--   messages      A message sent to/about a resident's care circle.
--   family_visits A scheduled or logged visit by a family member.
--
-- RLS: every table below has row level security enabled, with one
-- development policy granting signed-in (authenticated) users full read
-- and write access. The anon role has no policy on any of these tables,
-- so with RLS enabled it gets no access at all by default.

create extension if not exists pgcrypto;

-- facilities ------------------------------------------------------------

create table if not exists public.facilities (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  plan text,
  subscription_status text,
  created_at timestamptz not null default now()
);

alter table public.facilities enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'facilities'
      and policyname = 'facilities_authenticated_all'
  ) then
    -- Dev policy: any signed-in user can read/write; anon gets nothing.
    create policy "facilities_authenticated_all"
      on public.facilities
      for all
      to authenticated
      using (true)
      with check (true);
  end if;
end $$;

